def _frame_rgb(graph: str, src: Path, out: Path) -> np.ndarray:
    subprocess.run(["ffmpeg", "-v", "error", "-y", "-i", str(src), "-filter_complex", graph + ";[base]format=rgb24[v]",
                    "-map", "[v]", "-frames:v", "1", "-f", "rawvideo", str(out)], check=True)
    return np.frombuffer(out.read_bytes(), np.uint8).reshape(1920, 1080, 3)


@ffmpeg_only
@pytest.mark.parametrize("order", ["top", "bottom"])
def test_split_layout_pixels(tmp_path, order):
    """A blue 'game' with a pure green 'cam' in the bottom-right corner: the facecam panel must be
    green, the gameplay panel blue, in the chosen order, at 1080x1920."""
    src = tmp_path / "src.png"
    subprocess.run(["ffmpeg", "-v", "error", "-y", "-f", "lavfi", "-i", "color=c=0x0000ff:s=1280x720",
                    "-vf", "drawbox=x=960:y=504:w=282:h=180:color=0x00ff00:t=fill", "-frames:v", "1", str(src)],
                   check=True)
    fc = Facecam(x=960 / 1280, y=504 / 720, w=282 / 1280, h=180 / 720)
    sp = SplitSpec(cam_h=576, order=order, game_fit="crop", hide_cam=True)
    tok = clips._SPLIT.set(sp)
    try:
        px = _frame_rgb(clips._filter_graph("split", 1280, 720, fc), src, tmp_path / "f.rgb")
    finally:
        clips._SPLIT.reset(tok)
    cam_mid = sp.cam_y + sp.cam_h // 2
    game_mid = sp.game_y + sp.game_h // 2
    assert px.shape == (1920, 1080, 3)
    g = px[cam_mid - 50:cam_mid + 50, 300:780].mean(axis=(0, 1))
    b = px[game_mid - 50:game_mid + 50, 300:780].mean(axis=(0, 1))
    assert g[1] > 200 and g[2] < 60, g  # green facecam panel
    assert b[2] > 200 and b[1] < 60, b  # blue gameplay panel (the cam isn't shown twice in it)


