def _seg(n, t0, dur, wall0, gap=0.0):
    ws = wall0 + timedelta(seconds=t0 + gap)
    return liverec.Segment(n=n, file=f"seg_{n:06d}.ts", t0=t0, dur=dur, wall_start=ws.isoformat(),
                           wall_end=(ws + timedelta(seconds=dur)).isoformat(), run=1, bytes=1000)


def test_wall_clock_maps_onto_stream_time():
    w0 = datetime(2026, 1, 1, 12, 0, tzinfo=timezone.utc)
    segs = [_seg(0, 0, 6, w0), _seg(1, 6, 6, w0), _seg(2, 12, 6, w0, gap=30)]  # 30 s reconnect gap
    ts = lambda s: (w0 + timedelta(seconds=s)).timestamp()  # noqa: E731
    assert liverec.wall_to_t(segs, ts(-100)) == 0.0  # never negative
    assert liverec.wall_to_t(segs, ts(3)) == pytest.approx(3)
    assert liverec.wall_to_t(segs, ts(20)) == pytest.approx(12)  # inside the gap: next segment's start
    assert liverec.wall_to_t(segs, ts(45)) == pytest.approx(15)
    assert liverec.wall_to_t(segs, ts(60)) == pytest.approx(18 + 12)  # past the live edge: extrapolated


def test_retention_never_deletes_pinned_unanalyzed_or_newest():
    w0 = datetime(2026, 1, 1, tzinfo=timezone.utc)
    segs = [_seg(i, i * 60.0, 60.0, w0) for i in range(10)]  # 10 min
    pins = [{"t0": 90.0, "t1": 100.0}]
    out = liverec.deletable(segs, pins, "rolling", keep_s=300, analyzed_until=600)
    assert [s.n for s in out] == [0, 2, 3, 4]  # 1 is pinned; 5..9 are inside the last 5 min
    out = liverec.deletable(segs, pins, "rolling", keep_s=300, analyzed_until=150)
    assert [s.n for s in out] == [0, 2] or [s.n for s in out] == [0]  # not analyzed yet -> kept
    assert all(s.t1 <= 150 for s in out)
    assert liverec.deletable(segs, pins, "archive", keep_s=300, analyzed_until=600) == []
    emer = liverec.deletable(segs, pins, "archive", keep_s=300, analyzed_until=0, emergency=True)
    assert 1 not in [s.n for s in emer] and 9 not in [s.n for s in emer]


def test_low_disk_alarm_and_emergency_cleanup(tmp_path, monkeypatch):
    s = liverec.Session("t", tmp_path)
    s.seg_dir.mkdir(parents=True)
    w0 = datetime(2026, 1, 1, tzinfo=timezone.utc)
    for i in range(5):
        seg = _seg(i, i * 6.0, 6.0, w0)
        (s.seg_dir / seg.file).write_bytes(b"x" * 1000)
        s.segments.append(seg)
    s.info = {"settings": {**liverec.DEFAULTS, "retention": "rolling"}, "analyzed_until": 0.0}
    s.pin(0, 3, "candidate")
    free = {"v": 1e12}
    monkeypatch.setattr(liverec, "disk_free", lambda p: free["v"])
    d = s.apply_retention()
    assert not d["low"] and not d["critical"] and d["removed"] == 0  # 90 min window, nothing old
    free["v"] = 1e9  # 1 GB: below the 3 GB critical level
    d = s.apply_retention()
    assert d["low"] and d["critical"]
    assert s.segments[0].n == 0 and (s.seg_dir / "seg_000000.ts").is_file()  # pinned survives
    assert s.segments[-1].n == 4  # newest survives
    assert len(s.segments) == 2


