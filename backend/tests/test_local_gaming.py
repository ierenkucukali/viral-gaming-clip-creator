def test_split_spec_from_options_clamps_and_defaults():
    sp = SplitSpec.from_options(ClipOptions())
    assert (sp.cam_h, sp.order, sp.game_fit, sp.hide_cam) == (640, "top", "crop", True)  # 1/3
    assert SplitSpec.from_options(ClipOptions.from_dict({"split_ratio": 0.9})).cam_h == 768  # max 40 %
    assert SplitSpec.from_options(ClipOptions.from_dict({"split_ratio": 0.1})).cam_h == 480  # min 25 %
    bottom = SplitSpec.from_options(ClipOptions.from_dict({"split_order": "bottom"}))
    assert (bottom.cam_y, bottom.game_y, bottom.seam) == (1280, 0, 1280)
    with pytest.raises(SharkyClipsError):
        ClipOptions.from_dict({"split_order": "left"})
    with pytest.raises(SharkyClipsError):
        ClipOptions.from_dict({"game_fit": "stretch"})


@pytest.mark.parametrize("w,h", [(1920, 1080), (1280, 720), (2560, 1440)])
def test_normalized_facecam_gives_same_relative_crop_at_any_resolution(w, h):
    sp = SplitSpec(cam_h=576)
    cam, game = clips.split_rects(w, h, FC_BR, sp)
    # the cam crop stays inside the normalized box and keeps the panel's aspect ratio (no stretch)
    assert cam[0] >= FC_BR.x * w - 2 and cam[0] + cam[2] <= (FC_BR.x + FC_BR.w) * w + 2
    assert cam[1] >= FC_BR.y * h - 2 and cam[1] + cam[3] <= h
    assert cam[2] / cam[3] == pytest.approx(1080 / 576, rel=0.02)
    # gameplay crop: full height, the gameplay panel's aspect ratio
    assert game[3] == h and game[2] / game[3] == pytest.approx(1080 / (1920 - 576), rel=0.02)


def test_game_offset_and_fit_modes():
    left = clips.split_rects(1920, 1080, FC_BR, SplitSpec(cam_h=576, game_offset=-1.0))[1]
