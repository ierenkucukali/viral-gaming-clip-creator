def test_interrupted_download_is_retried(monkeypatch, tmp_path):
    """yt-dlp raises once mid-download (network): the import retries and finishes."""
    import yt_dlp

    from sharkyclips import ingest

    calls = {"download": 0}

    class FakeYDL:
        def __init__(self, opts):
            self.opts = opts

        def __enter__(self):
            return self

        def __exit__(self, *a):
            return False

        def extract_info(self, url, download=False):
            return {"id": "abcdefghijk", "title": "Retry test", "extractor_key": "Youtube",
                    "webpage_url": url, "duration": 10}

        def download(self, urls):
            calls["download"] += 1
            if calls["download"] == 1:
                raise yt_dlp.utils.DownloadError("ERROR: Connection reset by peer")
            Path(self.opts["outtmpl"].replace("%(ext)s", "mp4")).write_bytes(b"\0" * 64)

    monkeypatch.setattr(yt_dlp, "YoutubeDL", FakeYDL)
    monkeypatch.setattr(ingest.time, "sleep", lambda s: None)
    monkeypatch.setattr(ingest, "require_tool", lambda name: "/usr/bin/" + name)
    project, info = ingest._ingest_url("https://www.youtube.com/watch?v=abcdefghijk")
    assert calls["download"] == 2 and project.source_path is not None
    shutil.rmtree(project.dir, ignore_errors=True)


