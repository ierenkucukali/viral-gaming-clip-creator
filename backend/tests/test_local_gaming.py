def test_spike_candidates_preroll_wait_and_dedupe():
    lv = np.full(300, -40.0, np.float32)
    voice = np.full(300, 0.6, np.float32)
    lv[100:104] = -20.0  # a 4 s shout at 100 s
    lv[110:112] = -22.0  # a second burst 10 s later -> the same moment
    lv[280:282] = -18.0  # at the live edge: not fully recorded yet
    c = liverec.detect_spikes(lv, voice, until=285)
    assert len(c) == 1
    one = c[0]
    assert one["start"] <= 100 - 6 and one["end"] >= 112  # pre-roll kept, both bursts inside
    assert 15 <= one["end"] - one["start"] <= 60
    assert {r["code"] for r in one["reasons"]} >= {"loudness_spike", "voice"}
    c = liverec.detect_spikes(lv, voice, until=300)  # once the reaction is on disk it shows up
    assert len(c) == 2 and c[1]["peak"] >= 280
    quiet = np.full(300, -70.0, np.float32)
    quiet[100] = -58.0  # a "spike" in near-silence (menu screen) is ignored
    assert liverec.detect_spikes(quiet, voice, until=300) == []


