def _make_segments(dirpath: Path, seconds: int = 18, seg: int = 6) -> list[tuple[str, float]]:
    dirpath.mkdir(parents=True, exist_ok=True)
    csv = dirpath.parent / "list.csv"
    subprocess.run(["ffmpeg", "-v", "error", "-y", "-f", "lavfi", "-i", f"testsrc2=s=320x180:r=30:d={seconds}",
                    "-f", "lavfi", "-i", f"sine=f=440:d={seconds}", "-c:v", "libx264", "-g", "30", "-preset",
                    "ultrafast", "-c:a", "aac", "-shortest", "-f", "segment", "-segment_time", str(seg),
                    "-segment_format", "mpegts", "-segment_list", str(csv), "-segment_list_type", "csv",
                    "-reset_timestamps", "0", str(dirpath / "seg_%06d.ts")], check=True)
    got, _ = liverec.read_segment_csv(csv, 0)
    return got


def _probe(path: Path) -> dict:
    out = subprocess.run(["ffprobe", "-v", "error", "-show_entries",
                          "stream=codec_type,codec_name,width,height:format=duration", "-of", "json", str(path)],
                         capture_output=True, text=True, check=True)
    return json.loads(out.stdout)


